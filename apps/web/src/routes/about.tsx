function PersonNote({ person }: { person: (typeof people)[number] }) {
  return <HoverCard.Root openDelay={120} closeDelay={180}>
    <HoverCard.Trigger asChild>
      <button type="button" className="person-trigger" aria-label={`معرفی ${person.name}`}>{person.name}</button>
    </HoverCard.Trigger>
    <HoverCard.Portal>
      <HoverCard.Content className="person-note" sideOffset={10} collisionPadding={16}>
        <p className="person-note-label">یادداشت سپاس</p>
        <h2>{person.name}</h2>
        <p className="person-note-role">{person.role}</p>
        <p>{person.note}</p>
        <a href={person.href} target="_blank" rel="noreferrer">{person.source}</a>
        <HoverCard.Arrow className="person-note-arrow" />
      </HoverCard.Content>
    </HoverCard.Portal>
  </HoverCard.Root>
}

